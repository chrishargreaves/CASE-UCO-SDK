"""Search and detail lookup over the vendored adversary-technique catalogs.

Indexes ``extensions/attack-technique/mitre-attack-catalog.ttl`` (MITRE
ATT&CK: Enterprise, Mobile, ICS) and
``extensions/atlas-technique/mitre-atlas-catalog.ttl`` (MITRE ATLAS). Both
are generated by the sync tools in ``mcp_server/tools`` in the UCO 1.5.0
``uco-action:Technique`` metaclass pattern; this module only reads them.

These catalogs describe adversary tradecraft against computer and AI
systems. They are a separate vocabulary from SOLVE-IT (forensic practice,
see ``solveit_index``), the offense-conduct extensions, and CAC, and every
modeling hint returned here says so.
"""

from __future__ import annotations

import re
import threading
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import extension_paths

PROJECT_ROOT = Path(__file__).resolve().parent.parent

ACTION = "https://ontology.unifiedcyberontology.org/uco/action/"
DCTERMS = "http://purl.org/dc/terms/"
RDFS = "http://www.w3.org/2000/01/rdf-schema#"
OWL = "http://www.w3.org/2002/07/owl#"

# catalog key -> (extension name, catalog file, display name, technique namespace)
CATALOGS: dict[str, tuple[str, str, str, str]] = {
    "attack": (
        "attack-technique",
        "mitre-attack-catalog.ttl",
        "MITRE ATT&CK",
        "https://attack.mitre.org/techniques/",
    ),
    "atlas": (
        "atlas-technique",
        "mitre-atlas-catalog.ttl",
        "MITRE ATLAS",
        "https://atlas.mitre.org/techniques/",
    ),
}

EVIDENCE_GATE = (
    "Use a technique class only for behavior an artifact in the case shows "
    "(host, network, model, or log evidence of that tradecraft). ATT&CK and "
    "ATLAS are not combined with offense-conduct (trafficking, elder-fraud, "
    "extortion, trajectories), SOLVE-IT, or CAC vocabularies by default; "
    "see docs/recipes/cross-ontology-composition.md principle 6."
)

_TOKEN_RE = re.compile(r"[a-z0-9]+(?:\.[a-z0-9]+)*")


@dataclass
class TechniqueRecord:
    catalog: str
    technique_id: str
    iri: str
    name: str
    description: str
    parent_iri: str | None = None
    tactic_iris: list[str] = field(default_factory=list)
    platforms: list[str] = field(default_factory=list)
    matrix_iris: list[str] = field(default_factory=list)
    replaced_by_iris: list[str] = field(default_factory=list)
    see_also: list[str] = field(default_factory=list)
    deprecated: bool = False
    modified: str | None = None


@dataclass
class _Index:
    techniques: dict[str, TechniqueRecord]
    by_iri: dict[str, TechniqueRecord]
    tactics: dict[str, dict[str, str]]
    matrices: dict[str, dict[str, str]]
    children: dict[str, list[str]]
    versions: dict[str, str]


_LOCK = threading.Lock()
_CACHE: dict[tuple, _Index] = {}


def catalog_path(catalog: str, project_root: Path = PROJECT_ROOT) -> Path:
    ext_name, filename, _, _ = CATALOGS[catalog]
    return extension_paths.extension_dir(ext_name, project_root) / filename


def _load(project_root: Path) -> _Index:
    paths = {key: catalog_path(key, project_root) for key in CATALOGS}
    stamp = tuple(
        (key, str(p), p.stat().st_mtime_ns if p.is_file() else None)
        for key, p in sorted(paths.items())
    )
    with _LOCK:
        cached = _CACHE.get(stamp)
        if cached is not None:
            return cached
        if not any(p.is_file() for p in paths.values()):
            raise FileNotFoundError("no adversary technique catalog is vendored")

        import rdflib
        from rdflib.namespace import RDF

        techniques: dict[str, TechniqueRecord] = {}
        tactics: dict[str, dict[str, str]] = {}
        matrices: dict[str, dict[str, str]] = {}
        versions: dict[str, str] = {}
        technique_cls = rdflib.URIRef(f"{ACTION}Technique")
        technique_id = rdflib.URIRef(f"{ACTION}techniqueID")
        label = rdflib.URIRef(f"{RDFS}label")
        comment = rdflib.URIRef(f"{RDFS}comment")
        sub_class_of = rdflib.URIRef(f"{RDFS}subClassOf")
        see_also = rdflib.URIRef(f"{RDFS}seeAlso")
        deprecated = rdflib.URIRef(f"{OWL}deprecated")
        version_info = rdflib.URIRef(f"{OWL}versionInfo")
        subject = rdflib.URIRef(f"{DCTERMS}subject")
        coverage = rdflib.URIRef(f"{DCTERMS}coverage")
        is_part_of = rdflib.URIRef(f"{DCTERMS}isPartOf")
        replaced_by = rdflib.URIRef(f"{DCTERMS}isReplacedBy")
        identifier = rdflib.URIRef(f"{DCTERMS}identifier")
        modified = rdflib.URIRef(f"{DCTERMS}modified")

        for key, path in paths.items():
            if not path.is_file():
                continue
            g = rdflib.Graph()
            g.parse(str(path), format="turtle")
            for node in g.subjects(RDF.type, technique_cls):
                tid = str(g.value(node, technique_id) or "")
                if not tid:
                    continue
                parents = [
                    str(o) for o in g.objects(node, sub_class_of)
                    if str(o) != f"{ACTION}Action"
                ]
                techniques[tid] = TechniqueRecord(
                    catalog=key,
                    technique_id=tid,
                    iri=str(node),
                    name=str(g.value(node, label) or tid),
                    description=str(g.value(node, comment) or ""),
                    parent_iri=parents[0] if parents else None,
                    tactic_iris=sorted(str(o) for o in g.objects(node, subject)),
                    platforms=sorted(str(o) for o in g.objects(node, coverage)),
                    matrix_iris=sorted(str(o) for o in g.objects(node, is_part_of)),
                    replaced_by_iris=sorted(str(o) for o in g.objects(node, replaced_by)),
                    see_also=sorted(str(o) for o in g.objects(node, see_also)),
                    deprecated=bool(g.value(node, deprecated)),
                    modified=str(g.value(node, modified) or "") or None,
                )
            for node, ident in g.subject_objects(identifier):
                tactics[str(node)] = {
                    "id": str(ident),
                    "iri": str(node),
                    "name": str(g.value(node, label) or ident),
                    "description": str(g.value(node, comment) or ""),
                    "matrix_iri": str(g.value(node, is_part_of) or ""),
                    "catalog": key,
                }
            for node, ver in g.subject_objects(version_info):
                matrices[str(node)] = {
                    "iri": str(node),
                    "name": str(g.value(node, label) or node),
                    "version": str(ver),
                }
                versions[key] = str(ver)

        by_iri = {rec.iri: rec for rec in techniques.values()}
        children: dict[str, list[str]] = {}
        for rec in techniques.values():
            if rec.parent_iri and rec.parent_iri in by_iri:
                children.setdefault(by_iri[rec.parent_iri].technique_id, []).append(
                    rec.technique_id
                )
        for kids in children.values():
            kids.sort()
        index = _Index(techniques, by_iri, tactics, matrices, children, versions)
        _CACHE.clear()
        _CACHE[stamp] = index
        return index


def _catalog_key(catalog: str | None) -> str | None:
    if catalog is None or catalog == "":
        return None
    key = re.sub(r"[^a-z]", "", catalog.lower()).removeprefix("mitre")
    aliases = {"attack": "attack", "attck": "attack", "atlas": "atlas"}
    if key not in aliases:
        raise ValueError(f"unknown catalog {catalog!r}; use 'attack' or 'atlas'")
    return aliases[key]


def _tactic_refs(index: _Index, rec: TechniqueRecord) -> list[dict[str, str]]:
    out = []
    for iri in rec.tactic_iris:
        tactic = index.tactics.get(iri)
        matrix = index.matrices.get(tactic["matrix_iri"]) if tactic else None
        out.append(
            {
                "id": tactic["id"] if tactic else iri.rsplit("/", 1)[-1],
                "name": tactic["name"] if tactic else "",
                "iri": iri,
                "matrix": matrix["name"] if matrix else "",
            }
        )
    return out


def _summary(index: _Index, rec: TechniqueRecord) -> dict[str, Any]:
    payload: dict[str, Any] = {
        "id": rec.technique_id,
        "catalog": CATALOGS[rec.catalog][2],
        "iri": rec.iri,
        "name": rec.name,
        "tactics": [t["name"] for t in _tactic_refs(index, rec)],
        "matrices": [index.matrices[m]["name"] for m in rec.matrix_iris if m in index.matrices],
        "deprecated": rec.deprecated,
    }
    if rec.parent_iri and rec.parent_iri in index.by_iri:
        payload["parent"] = index.by_iri[rec.parent_iri].technique_id
    return payload


def search(
    query: str,
    *,
    catalog: str | None = None,
    tactic: str | None = None,
    platform: str | None = None,
    include_deprecated: bool = False,
    limit: int = 10,
    project_root: Path = PROJECT_ROOT,
) -> dict[str, Any]:
    """Rank catalog techniques for a keyword query or identifier."""

    index = _load(project_root)
    key = _catalog_key(catalog)
    q = (query or "").strip()
    q_lower = q.lower()
    tokens = [t for t in _TOKEN_RE.findall(q_lower) if len(t) > 1]
    tactic_lower = (tactic or "").strip().lower()
    platform_lower = (platform or "").strip().lower()
    limit = max(1, min(int(limit), 50))

    scored: list[tuple[float, str]] = []
    for tid, rec in index.techniques.items():
        if key and rec.catalog != key:
            continue
        if rec.deprecated and not include_deprecated and tid.upper() != q.upper():
            continue
        tactic_refs = _tactic_refs(index, rec)
        if tactic_lower and not any(
            tactic_lower in (t["name"].lower(), t["id"].lower()) for t in tactic_refs
        ):
            continue
        if platform_lower and not any(platform_lower == p.lower() for p in rec.platforms):
            continue
        if not tokens:
            scored.append((0.0, tid))
            continue
        name = rec.name.lower()
        desc = rec.description.lower()
        tactic_text = " ".join(t["name"].lower() for t in tactic_refs)
        score = 0.0
        if tid.lower() == q_lower:
            score += 100.0
        elif tid.lower().startswith(q_lower) and "." in tid and "." not in q_lower:
            score += 20.0
        if q_lower and q_lower in name:
            score += 10.0
        for token in tokens:
            if token in name:
                score += 3.0
            if token in tactic_text:
                score += 1.5
            if token in desc:
                score += 1.0
        if score > 0:
            if rec.deprecated:
                score *= 0.5
            scored.append((score, tid))

    scored.sort(key=lambda item: (-item[0], item[1]))
    results = [_summary(index, index.techniques[tid]) for _, tid in scored[:limit]]
    return {
        "query": q,
        "catalog_versions": {
            CATALOGS[k][2]: v for k, v in sorted(index.versions.items())
        },
        "total_matches": len(scored),
        "results": results,
        "next_step": "get_adversary_technique(id) for the full record and modeling guidance",
        "evidence_gate": EVIDENCE_GATE,
    }


def details(technique_id: str, *, project_root: Path = PROJECT_ROOT) -> dict[str, Any]:
    """Full record for one ATT&CK (``T1027.002``) or ATLAS (``AML.T0051``) ID."""

    index = _load(project_root)
    tid = (technique_id or "").strip()
    rec = index.techniques.get(tid) or index.techniques.get(tid.upper())
    if rec is None:
        rec = index.by_iri.get(tid)
    if rec is None:
        raise KeyError(tid)

    ext_name = CATALOGS[rec.catalog][0]
    parent = index.by_iri.get(rec.parent_iri or "")
    related = [
        _summary(index, index.by_iri[url]) for url in rec.see_also if url in index.by_iri
    ]
    replaced_by = [
        _summary(index, index.by_iri[iri]) for iri in rec.replaced_by_iris if iri in index.by_iri
    ]
    payload: dict[str, Any] = {
        **_summary(index, rec),
        "description": rec.description,
        "tactics": _tactic_refs(index, rec),
        "platforms": rec.platforms,
        "parent": _summary(index, parent) if parent else None,
        "subtechniques": [
            _summary(index, index.techniques[c]) for c in index.children.get(rec.technique_id, [])
        ],
        "replaced_by": replaced_by,
        "related_techniques": related,
        "see_also": [url for url in rec.see_also if url not in index.by_iri],
        "modified": rec.modified,
        "catalog_version": index.versions.get(rec.catalog),
        "extension": ext_name,
        "modeling_guidance": {
            "pattern": (
                "Type the uco-action:Action node that the evidence shows with "
                "this technique class (rdf:type, the UCO 1.5.0 "
                "uco-action:Technique metaclass pattern). Do not create an "
                "instance node for the technique or a Relationship to it; the "
                "type edge is the association. A sub-technique already "
                "specializes its parent, so do not also type the parent."
            ),
            "example_jsonld": {
                "@id": "kb:action-<uuid>",
                "@type": ["uco-action:Action", rec.iri],
                "uco-action:performer": {"@id": "kb:<actor>"},
                "uco-action:object": [{"@id": "kb:<observable evidence>"}],
            },
            "validate_with": {"extensions": [ext_name]},
            "evidence_gate": EVIDENCE_GATE,
            "recipe": (
                "docs/recipes/ai-system-attacks.md"
                if rec.catalog == "atlas"
                else "docs/recipes/cyber-threat-intelligence.md"
            ),
        },
    }
    if rec.deprecated:
        payload["modeling_guidance"]["deprecation"] = (
            "MITRE deprecated or revoked this technique. Keep it only when the "
            "source cites this ID; otherwise use the replacement"
            + (f" ({', '.join(r['id'] for r in replaced_by)})" if replaced_by else "")
            + "."
        )
    return payload
