# --- Writes (#56) -------------------------------------------------------------


@pytest.mark.parametrize("concept", ["....", "/", "   ", "§§"])
def test_empty_slug_is_a_typed_error(tmp_path: Path, concept: str) -> None:
    result = _draft(tmp_path, concept=concept)
    assert result["ok"] is False and result["error"] == "proposal_slug_empty"
    assert list(tmp_path.iterdir()) == []


def test_traversal_in_concept_stays_in_output_dir(tmp_path: Path) -> None:
    result = _draft(tmp_path, concept="../../etc/passwd")
    assert Path(result["file_path"]).parent == tmp_path.resolve()


def test_writes_outside_write_roots_are_refused(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    allowed = tmp_path / "allowed"
    allowed.mkdir()
    elsewhere = tmp_path / "elsewhere"
    monkeypatch.setenv(workspace_policy.WRITE_ROOTS_ENV, str(allowed))
    result = _draft(tmp_path, output_dir=str(elsewhere))
    assert result["ok"] is False and result["error"] == "proposal_outside_write_roots"
    assert not elsewhere.exists()
    result = _draft(tmp_path, output_dir=str(allowed))
    assert result["ok"] is True
    assert Path(result["file_path"]).parent == allowed.resolve()
