def _draft(tmp_path: Path, **overrides):
    kwargs = {**BASE, "output_dir": str(tmp_path), **overrides}
    return draft(**kwargs)


def _codes(result) -> set[str]:
    return {finding["code"] for finding in result["lint"]}


# --- Format and provenance ---------------------------------------------------


def test_body_follows_discussion_draft_format(tmp_path: Path) -> None:
    result = _draft(tmp_path)
    assert result["ok"] is True
    assert result["ready_to_file"] is True
    body = Path(result["file_path"]).read_text(encoding="utf-8")
    assert body == result["content"]
    lines = body.splitlines()
    assert lines[0] == f"<!-- Change proposal: {BASE['concept']} -->"
    assert lines[1] == "<!-- Target repository: CASE -->"
    assert "Drafted with" not in body and "Generated by" not in body
    assert "**Suggested target release:** CASE/UCO 1.6.0  " in lines
    assert (
        "**Contributor:** Cory Hall (@vulnmaster) with the assistance of the CASE/UCO SDK "
        "MCP/Agent (v" in body
    )
    assert ") powered by Claude Opus 5.5 High" in body
    assert cp.DISCUSSION_DRAFT_NOTE in body and cp.PROVENANCE_LEGEND in body
    for heading in (
        "# Background",
        "# Competency questions",
        "## CQ 1",
        "# Requirements",
        "## Term 1: Legislation (schema.org)",
        "# Open questions",
        "# Related issues and references",
    ):
        assert heading in lines
    assert "<details>" in body and "<summary><b>Committee section</b>" in body
    assert body.count(f"\n{cp.COMMITTEE_PLACEHOLDER}\n") == 3


